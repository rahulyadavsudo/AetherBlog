export type UserRole = 'admin' | 'writer';

export interface User {
  id: string;
  name: string;
  email: string;
  avatar: string;
  role: UserRole;
  title: string;
  bio: string;
}

export type PostStatus = 'draft' | 'published' | 'scheduled' | 'archived';

export interface PostMetrics {
  views: number;
  uniqueVisitors: number;
  avgReadTime: string; // e.g. "4m 12s"
  readRatio: number; // e.g. 76 (%)
  claps: number;
  shares: number;
  bookmarks: number;
  viewsHistory: { date: string; views: number; reads: number }[];
  referrers: { source: string; percentage: number; count: number }[];
  deviceBreakdown: { mobile: number; desktop: number; tablet: number };
  // Multi-language microservice telemetry
  nlpSentiment?: string;
  readabilityGrade?: string;
  processedBy?: string;
}

export interface PostRevision {
  id: string;
  timestamp: string;
  authorName: string;
  summary: string;
  wordCount: number;
  content: string;
}

export interface Collaborator {
  userId: string;
  name: string;
  avatar: string;
  role: string;
  color: string;
  activeNow: boolean;
  cursorLine?: number;
  statusText?: string;
}

export interface PostComment {
  id: string;
  authorName: string;
  authorAvatar: string;
  authorRole: string;
  content: string;
  createdAt: string;
  resolved?: boolean;
}

export interface EncryptedPackage {
  ciphertext: string;
  iv: string;
  salt: string;
  algorithm: string;
  tagLength: number;
  encryptedAt: string;
}

export interface Post {
  id: string;
  title: string;
  slug: string;
  summary: string;
  content: string; // raw markdown or decrypted plaintext
  coverImage?: string;
  status: PostStatus;
  authorId: string;
  authorName: string;
  authorAvatar: string;
  authorRole: UserRole;
  category: string;
  tags: string[];
  publishedAt?: string;
  createdAt: string;
  updatedAt: string;
  readTime: number; // minutes
  wordCount: number;
  isEncrypted: boolean;
  encryptedPackage?: EncryptedPackage;
  metrics: PostMetrics;
  revisions: PostRevision[];
  collaborators: Collaborator[];
  comments: PostComment[];
}

export interface ActivityLog {
  id: string;
  timestamp: string;
  action: 
    | 'AUTH_LOGIN'
    | 'AUTH_LOGOUT'
    | 'POST_CREATED'
    | 'POST_UPDATED'
    | 'POST_PUBLISHED'
    | 'POST_ARCHIVED'
    | 'POST_DELETED'
    | 'E2EE_ENCRYPT'
    | 'E2EE_DECRYPT'
    | 'BACKUP_SYNC'
    | 'BACKUP_RESTORE'
    | 'COLLAB_JOIN'
    | 'ROLE_UPDATED'
    | 'MICROSERVICE_DISPATCH';
  actorName: string;
  actorRole: UserRole;
  details: string;
  entityId?: string;
  status: 'success' | 'warning' | 'info';
}

export interface BackupSnapshot {
  id: string;
  timestamp: string;
  postCount: number;
  sizeBytes: number;
  hash: string;
  autoGenerated: boolean;
  data: string; // JSON snapshot of all posts
}

export interface MicroserviceNode {
  id: string;
  name: string;
  language: 'Python' | 'Rust' | 'Go' | 'Node.js';
  role: string;
  port: number;
  status: 'healthy' | 'idle' | 'processing';
  latencyMs: number;
  uptimeSeconds: number;
  requestsCount: number;
  runtimeVersion: string;
  description: string;
}
